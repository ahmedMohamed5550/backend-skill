    /**
     * Verify the email address with a signed verification link.
     *
     * @OA\Get(
     *     path="/api/v1/auth/email/verify/{uuid}/{hash}",
     *     operationId="authVerifyEmail",
     *     tags={"Auth"},
     *     summary="Verify email",
     *     description="Consume the signed verification link of Laravel's native email verification flow (the framework's VerifyEmail notification builds exactly this URL and emails it — the link addresses the user by uuid). The request is authorized by its cryptographic signature — the ValidateSignature middleware rejects expired or tampered links with 403 before this action runs, exactly like Laravel's own verification flow, because an email client cannot present a Bearer token. The hash must equal sha1(email) of the addressed user. Success stamps email_verified_at and dispatches the native Verified event; following the link again stays idempotently successful.<br><br>🌐 <b>Public endpoint</b> (signed link — no Bearer token required)",
     *     x={"required-permission": null},
     *
     *     @OA\Parameter(
     *         name="uuid",
     *         in="path",
     *         required=true,
     *         description="The uuid of the user addressed by the verification link",
     *
     *         @OA\Schema(type="string", format="uuid")
     *     ),
     *     @OA\Parameter(
     *         name="hash",
     *         in="path",
     *         required=true,
     *         description="sha1(email) of the addressed user, as embedded by the verification email",
     *
     *         @OA\Schema(type="string", example="e0d0e3fda0b2e8cb7e2f47a1c22c08d5d1b9d3fa")
     *     ),
     *     @OA\Parameter(
     *         name="expires",
     *         in="query",
     *         required=true,
     *         description="Signature expiry timestamp (part of the emailed signed URL; 60 minutes by default)",
     *
     *         @OA\Schema(type="integer", example=1735689600)
     *     ),
     *     @OA\Parameter(
     *         name="signature",
     *         in="query",
     *         required=true,
     *         description="The HMAC signature of the signed URL (part of the emailed link)",
     *
     *         @OA\Schema(type="string")
     *     ),
     *
     *     @OA\Response(
     *         response=200,
     *         description="Email verified successfully (or the link was already consumed)",
     *
     *         @OA\JsonContent(
     *             @OA\Property(property="message", type="string", example="The email address has been verified successfully."),
     *             @OA\Property(property="status_code", type="integer", example=200),
     *             @OA\Property(property="data", type="object", example={})
     *         )
     *     ),
     *     @OA\Response(response=403, description="Invalid signature — the link expired (60 minutes) or was tampered with"),
     *     @OA\Response(response=404, description="No user exists for the link uuid"),
     *     @OA\Response(response=422, description="The hash does not match the addressed user's email")
     * )
     */
    public function verifyEmail(Request $request, string $uuid, string $hash): JsonResponse
    {
        try {
            $this->authService->verifyEmail($uuid, $hash);

            return $this->apiResponse(__('messages.email_verified_successfully'), 200, []);
        } catch (ValidationException $e) {
            throw $e;
        } catch (ModelNotFoundException) {
            return $this->apiResponse(__('messages.not_found'), 404, []);
        } catch (\Throwable $e) {
            Log::error('Email verification failed: '.$e->getMessage());

            return $this->apiResponse(__('messages.server_error'), 500, []);
        }
    }

