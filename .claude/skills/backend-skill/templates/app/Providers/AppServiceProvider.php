<?php

namespace App\Providers;

use App\Models\V1\User;
use Illuminate\Auth\Notifications\ResetPassword;
use Illuminate\Auth\Notifications\VerifyEmail;
use Illuminate\Cache\RateLimiting\Limit;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\RateLimiter;
use Illuminate\Support\Facades\Route;
use Illuminate\Support\Facades\URL;
use Illuminate\Support\ServiceProvider;
use Laravel\Passport\Http\Controllers\AccessTokenController;
use Laravel\Passport\Passport;

class AppServiceProvider extends ServiceProvider
{
    /**
     * Register any application services.
     */
    public function register(): void
    {
        // Passport route hardening (references/authentication.md): disable
        // Passport's automatically registered routes. This backend is
        // API-only — the browser authorize/consent flow (which would accept
        // league's default plain PKCE verifier), the transient token
        // refresh, the personal-token/scope endpoints, and the device grant
        // have no first-party consumer and must not exist. The call belongs
        // in register(): every provider's register() completes before any
        // boot(), so the flag is already set when PassportServiceProvider
        // boot() decides whether to register its routes.
        Passport::ignoreRoutes();
    }

    /**
     * Bootstrap any application services.
     */
    public function boot(): void
    {
        // Token lifetimes for the OAuth token lifecycle (references/
        // authentication.md, Token Lifecycle). Passport reads these values
        // when it resolves its authorization server, so setting them in
        // boot() covers both the login code exchange and every refresh.
        Passport::tokensExpireIn(now()->addMinutes((int) config('oauth.access_token_expires_in')));
        Passport::refreshTokensExpireIn(now()->addDays((int) config('oauth.refresh_token_expires_in')));

        // The single OAuth endpoint the token lifecycle uses, registered by
        // the application because Passport's routes are ignored above.
        // Passport's AccessTokenController resolves the PSR-7 request via
        // the framework's global ServerRequestInterface binding, so no extra
        // PSR-7 setup is required. `throttle` preserves Passport's own rate
        // limiting on the token endpoint.
        Route::post('/oauth/token', [AccessTokenController::class, 'issueToken'])
            ->middleware('throttle')
            ->name('passport.token');

        // Password reset link URL (references/authentication.md, Password
        // Reset): the native ResetPassword notification looks up a
        // password.reset web route that does not exist in this API-only
        // project, so the URL builder is pointed at the frontend page that
        // completes the flow by calling POST /api/v1/auth/reset-password.
        // FRONTEND_URL defaults to the API URL until a frontend exists; the
        // hashed, expiring token itself is generated by the native broker.
        ResetPassword::createUrlUsing(function (User $user, string $token): string {
            $frontendUrl = rtrim((string) config('app.frontend_url', config('app.url')), '/');

            return $frontendUrl.'/reset-password'
                .'?token='.$token
                .'&email='.urlencode($user->getEmailForPasswordReset());
        });

        // Email verification link URL (references/authentication.md, Email
        // Verification): public API identifiers are UUIDs, never database
        // ids, so the verification link addresses the user by uuid — but the
        // framework's VerifyEmail notification builds its signed URL with
        // the database id by default, which would throw a
        // MissingRouteParameterException against the {uuid} route the moment
        // a notification is mailed. createUrlUsing() is Laravel's official
        // URL customization hook: it swaps the id parameter for the uuid
        // while everything else stays native — the same notification, the
        // verification.verify route name, the 60-minute expiry from
        // auth.verification.expire, the sha1(email) hash, and the signed
        // middleware. Do not remove this registration.
        VerifyEmail::createUrlUsing(function (User $user): string {
            return URL::temporarySignedRoute(
                'verification.verify',
                now()->addMinutes((int) config('auth.verification.expire', 60)),
                [
                    'uuid' => $user->uuid,
                    'hash' => sha1($user->getEmailForVerification()),
                ],
            );
        });

        // Rate limiters (references/api-standards.md, Rate Limiting).
        // `api` is the baseline limiter bound to the api middleware group by
        // $middleware->throttleApi() in bootstrap/app.php: every /api/v1
        // request is limited per authenticated user id, or per IP for
        // guests. Values come from config/rate_limiting.php.
        RateLimiter::for('api', fn (Request $request) => Limit::perMinute(
            (int) config('rate_limiting.api_per_minute')
        )->by($request->user()?->id ?: $request->ip()));

        // `auth` guards the sensitive public auth endpoints (attached as
        // throttle:auth on the login route) with two independent buckets —
        // one per normalized (trimmed, lowercased) email and one per IP —
        // each with a per-minute and a per-hour window. All four limits
        // must pass for the request to proceed: the per-email bucket stops
        // one account being attacked from many IPs, the per-IP bucket stops
        // many accounts being attacked from one IP.
        RateLimiter::for('auth', function (Request $request) {
            // The limiter runs before validation, so its normalization must
            // tolerate non-string input: a non-scalar email (e.g. email[]=x
            // from a hostile client) would crash the (string) cast into a
            // 500 instead of reaching the 422 validation answer. Non-string
            // input lands in the shared empty-email bucket.
            $email = $request->input('email');
            $emailKey = sha1(mb_strtolower(trim(is_string($email) ? $email : '')));
            $ipKey = (string) $request->ip();
            $perMinute = (int) config('rate_limiting.auth_per_minute');
            $perHour = (int) config('rate_limiting.auth_per_hour');

            return [
                Limit::perMinute($perMinute)->by('email|'.$emailKey),
                Limit::perHour($perHour)->by('hour|email|'.$emailKey),
                Limit::perMinute($perMinute)->by('ip|'.$ipKey),
                Limit::perHour($perHour)->by('hour|ip|'.$ipKey),
            ];
        });

        // `password_reset` guards the public password reset endpoints
        // (attached as throttle:password_reset on forgot-password and
        // reset-password — references/authentication.md, Password Reset).
        // It mirrors the `auth` limiter: two independent buckets, one per
        // normalized email and one per IP, each with a per-minute and a
        // per-hour window. Values come from the reserved
        // password_reset_* keys of config/rate_limiting.php.
        RateLimiter::for('password_reset', function (Request $request) {
            // Same pre-validation robustness as `auth`: non-scalar email
            // input lands in the shared empty-email bucket instead of
            // crashing the (string) cast into a 500.
            $email = $request->input('email');
            $emailKey = sha1(mb_strtolower(trim(is_string($email) ? $email : '')));
            $ipKey = (string) $request->ip();
            $perMinute = (int) config('rate_limiting.password_reset_per_minute');
            $perHour = (int) config('rate_limiting.password_reset_per_hour');

            return [
                Limit::perMinute($perMinute)->by('email|password-reset|'.$emailKey),
                Limit::perHour($perHour)->by('hour|email|password-reset|'.$emailKey),
                Limit::perMinute($perMinute)->by('ip|password-reset|'.$ipKey),
                Limit::perHour($perHour)->by('hour|ip|password-reset|'.$ipKey),
            ];
        });

        // `email_resend` guards the authenticated resend-verification
        // endpoint (references/authentication.md, Email Verification). The
        // request carries no email body field, so the buckets key per
        // authenticated user id (never a shared bucket across users).
        RateLimiter::for('email_resend', function (Request $request) {
            $userKey = (string) ($request->user()?->id ?: $request->ip());
            $perMinute = (int) config('rate_limiting.email_resend_per_minute');
            $perHour = (int) config('rate_limiting.email_resend_per_hour');

            return [
                Limit::perMinute($perMinute)->by('email-resend|'.$userKey),
                Limit::perHour($perHour)->by('hour|email-resend|'.$userKey),
            ];
        });
    }
}
