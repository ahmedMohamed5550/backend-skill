    /**
     * Request a password reset link.
     *
     * @OA\Post(
     *     path="/api/v1/auth/forgot-password",
     *     operationId="authForgotPassword",
     *     tags={"Auth"},
     *     summary="Forgot password",
     *     description="Send a password reset link through Laravel's native Password broker. The link carries a hashed, expiring token (60 minutes, config auth.passwords.users.expire) and lands on the frontend reset-password page configured through FRONTEND_URL; the frontend completes the flow by calling POST /api/v1/auth/reset-password. The response is deliberately identical whether or not the email is registered — the endpoint never reveals whether an account exists. The native broker throttle answers 429 when the same address requests a second link within 60 seconds.<br><br>🌐 <b>Public endpoint</b>",
     *     x={"required-permission": null},
     *
     *     @OA\RequestBody(
     *         required=true,
     *
     *         @OA\JsonContent(
     *             required={"email"},
     *
     *             @OA\Property(property="email", type="string", format="email", example="admin@example.local")
     *         )
     *     ),
     *
     *     @OA\Response(
     *         response=200,
     *         description="Password reset link sent (neutral answer — identical for registered and unknown addresses)",
     *
     *         @OA\JsonContent(
     *             @OA\Property(property="message", type="string", example="If the email address is registered, a password reset link has been sent to it."),
     *             @OA\Property(property="status_code", type="integer", example=200),
     *             @OA\Property(property="data", type="object", example={})
     *         )
     *     ),
     *     @OA\Response(response=422, description="Validation failed (invalid email address)"),
     *     @OA\Response(response=429, description="Too many requests — the throttle:password_reset limiter or the native broker throttle (60 seconds per email) tripped; standard envelope with the Retry-After header")
     * )
     */
    public function forgotPassword(ForgotPasswordRequest $request): JsonResponse
    {
        try {
            $this->authService->sendPasswordResetLink($request->validated());

            return $this->apiResponse(__('messages.password_reset_link_sent'), 200, []);
        } catch (ValidationException $e) {
            throw $e;
        } catch (HttpExceptionInterface $e) {
            // The native broker throttle (429, references/authentication.md,
            // Password Reset): rendered by the central exception handler,
            // which keeps the envelope and the Retry-After header.
            throw $e;
        } catch (\Throwable $e) {
            Log::error('Password reset link request failed: '.$e->getMessage());

            return $this->apiResponse(__('messages.server_error'), 500, []);
        }
    }

