    }

    /**
     * Register a new user and send the verification email.
     *
     * @OA\Post(
     *     path="/api/v1/auth/register",
     *     operationId="authRegister",
     *     tags={"Auth"},
     *     summary="Register",
     *     description="Create a new user account and automatically send Laravel's native VerifyEmail notification (the user is created inside a database transaction; the email goes out only after it commits). The email carries the signed verification link GET /api/v1/auth/email/verify/{uuid}/{hash}, valid for 60 minutes. The endpoint does not authenticate the caller and issues no tokens — log in afterwards through POST /api/v1/auth/login and the POST /oauth/token exchange. A duplicate email address answers 422 (unique validation).<br><br>🌐 <b>Public endpoint</b>",
     *     x={"required-permission": null},
     *
     *     @OA\RequestBody(
     *         required=true,
     *
     *         @OA\JsonContent(
     *             required={"name", "email", "password", "password_confirmation"},
     *
     *             @OA\Property(property="name", type="string", maxLength=255, example="Jane Doe"),
     *             @OA\Property(property="email", type="string", format="email", example="jane@example.local", description="Must be unique across users"),
     *             @OA\Property(property="password", type="string", format="password", minLength=8, example="secret-password"),
     *             @OA\Property(property="password_confirmation", type="string", format="password", example="secret-password")
     *         )
     *     ),
     *
     *     @OA\Response(
     *         response=201,
     *         description="Account registered successfully; the verification email has been sent automatically",
     *
     *         @OA\JsonContent(
     *             @OA\Property(property="message", type="string", example="Account registered successfully. A verification email has been sent to your email address."),
     *             @OA\Property(property="status_code", type="integer", example=201),
     *
     *             @OA\Property(
     *                 property="data",
     *                 type="object",
     *
     *                 @OA\Property(property="uuid", type="string", format="uuid"),
     *                 @OA\Property(property="name", type="string"),
     *                 @OA\Property(property="email", type="string", format="email"),
     *                 @OA\Property(property="email_verified_at", type="string", nullable=true, format="date-time", example=null, description="Always null at registration — the email is verified by following the emailed link")
     *             )
     *         )
     *     ),
     *     @OA\Response(response=422, description="Validation failed (validation rules or a duplicate email address)"),
     *     @OA\Response(response=429, description="Too many attempts — the throttle:auth limits per normalized email and per IP (5/minute and 30/hour) exceeded; standard envelope with the Retry-After header")
     * )
     */
    public function register(RegisterRequest $request): JsonResponse
    {
        try {
            $user = $this->authService->register($request->validated());

            return $this->apiResponse(__('messages.registered'), 201, [
                'uuid' => $user->uuid,
                'name' => $user->name,
                'email' => $user->email,
                'email_verified_at' => $user->email_verified_at?->toISOString(),
            ]);
        } catch (ValidationException $e) {
            throw $e;
        } catch (\Throwable $e) {
            Log::error('Registration failed: '.$e->getMessage());

            return $this->apiResponse(__('messages.server_error'), 500, []);
        }
    }

    /**
